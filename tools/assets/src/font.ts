export const GLYPH_W = 5
export const GLYPH_H = 8
export const ADVANCE = GLYPH_W + 1

const BLANK = Array<string>(GLYPH_H).fill('.....')
const FALLBACK = '##### #...# #...# #...# #...# #...# #####'

const parse = (raw: string): string[] => {
  const rows = raw === '' ? [] : raw.split(' ')
  return BLANK.map((b, i) => rows[i] ?? b)
}

const GLYPHS = new Map(Object.entries(RAW).map(([ch, raw]) => [ch, parse(raw)]))

export const glyph = (ch: string): string[] => GLYPHS.get(ch) ?? parse(FALLBACK)
